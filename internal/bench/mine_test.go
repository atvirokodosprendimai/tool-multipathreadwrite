import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func salted(key string) string {
	s := sha256.Sum256([]byte("adr-160:" + key))
	return hex.EncodeToString(s[:])
}

// TestAWideRenameCandidateIsDeclaredOnceAndNeverInAString holds ADR-160's
// wide-rename predicate on a fixture module, with floors of 4 occurrences
// across 2 files: an identifier declared twice, one named in a string, one
// named in a generated file, one used as a package name and one under the floor
// are refused; one mentioned in comments qualifies with its comments counted.
// A name used as a selector on a standard-library value (Header) cannot be told
// apart without types, so it is listed: T2's build gate is what filters it.
func TestAWideRenameCandidateIsDeclaredOnceAndNeverInAString(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":   "module example.com/m\n\ngo 1.22\n",
		"a/a.go":   "package a\n\nimport \"net/http\"\n\n// Good does the thing; Good is documented.\nfunc Good() int { return Other + Twice }\n\n// Other is a constant.\nconst Other = 1\n\nvar Twice = 2\n\nfunc InString() string { return \"InString\" }\n\nfunc InGen() {}\n\nfunc Low() {}\n\ntype T struct{ Header int }\n\nfunc h(r *http.Response) int { _ = r.Header; return T{}.Header + Other }\n",
		"b/b.go":   "package b\n\nimport \"example.com/m/a\"\n\nfunc use() int {\n\tTwice := 3\n\ta.InGen()\n\ta.InString()\n\treturn a.Good() + a.Good() + a.Other + a.Other + Twice\n}\n\nfunc header(t a.T) int { return t.Header + t.Header }\n",
		"b/gen.go": "// Code generated by fixture. DO NOT EDIT.\n\npackage b\n\nfunc gen() { _ = a.InGen }\n",
		"c/c.go":   "package c\n\nimport \"example.com/m/a\"\n\n// uses Good again\nfunc again() int { a.InGen(); return a.Good() + a.Other }\n",
	})
	got, err := MineWideRenames(root, 4, 2)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, c := range got {
		names = append(names, c.Name)
	}
	for _, refused := range []string{"Twice", "InString", "InGen", "Low", "a", "http"} {
		if slices.Contains(names, refused) {
			t.Errorf("%s is listed; the predicate refuses it", refused)
		}
	}
	for _, want := range []string{"Good", "Other", "Header"} {
		if !slices.Contains(names, want) {
			t.Errorf("%s is not listed; it meets the predicate (%v)", want, got)
		}
	}
	for _, c := range got {
		if c.Name == "Good" && (c.Occurrences != 7 || c.Files != 3) {
			t.Errorf("Good: %d occurrences in %d files, want 7 in 3 (its two comment mentions in a.go and one in c.go counted)", c.Occurrences, c.Files)
		}
	}
	if !slices.IsSortedFunc(got, func(x, y RenameCandidate) int { return strings.Compare(salted(x.Name), salted(y.Name)) }) {
		t.Errorf("candidates are not in sha256(\"adr-160:\" + name) order: %v", names)
	}
}

// TestACheckCoupledCandidateIsALiteralSubstitutionWithItsTest holds ADR-160's
// check-coupled predicate on a fixture history: a commit that only replaces
// one literal's text in a source file and its test is listed; one that also
// changes code, one with no test file, one whose test is in another package,
// and one of five files are not.
func TestACheckCoupledCandidateIsALiteralSubstitutionWithItsTest(t *testing.T) {
	needGit(t)
	repo := t.TempDir()
	if err := git(repo, "init", "-q"); err != nil {
		t.Fatal(err)
	}
	commit := func(msg string, files map[string]string) string {
		t.Helper()
		writeTree(t, repo, files)
		if err := git(repo, "add", "-A"); err != nil {
			t.Fatal(err)
		}
		if err := git(repo, "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", "commit", "-q", "-m", msg); err != nil {
			t.Fatal(err)
		}
		sha, err := gitOut(repo, "rev-parse", "HEAD")
		if err != nil {
			t.Fatal(err)
		}
		return strings.TrimSpace(sha)
	}
	src := func(msg string) string { return "package p\n\nfunc Msg() string { return \"" + msg + "\" }\n" }
	test := func(msg string) string {
		return "package p\n\nimport \"testing\"\n\nfunc TestMsg(t *testing.T) {\n\tif Msg() != \"" + msg + "\" {\n\t\tt.Fatal(\"x\")\n\t}\n}\n"
	}
	commit("base", map[string]string{"p/p.go": src("old text"), "p/p_test.go": test("old text"), "q/q.go": src("left"), "r/r.go": src("other"), "s/s_test.go": "package s\n\nconst want = \"other\"\n",
		"f/1.go": src("five"), "f/2.go": src("five"), "f/3.go": src("five"), "f/4.go": src("five"), "f/4_test.go": test("five")})
	good := commit("rename the message", map[string]string{"p/p.go": src("new text"), "p/p_test.go": test("new text")})
	commit("message and code", map[string]string{"p/p.go": src("newer text") + "\nfunc Extra() {}\n", "p/p_test.go": test("newer text")})
	commit("no test", map[string]string{"q/q.go": src("right")})
	commit("test elsewhere", map[string]string{"r/r.go": src("another"), "s/s_test.go": "package s\n\nconst want = \"another\"\n"})
	commit("five files", map[string]string{"f/1.go": src("six"), "f/2.go": src("six"), "f/3.go": src("six"), "f/4.go": src("six"), "f/4_test.go": test("six")})
	got, err := MineCheckCoupled(repo, "HEAD", 4)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 || got[0].Commit != good || got[0].Old != "old text" || got[0].New != "new text" ||
		!slices.Equal(got[0].Files, []string{"p/p.go", "p/p_test.go"}) {
		t.Fatalf("candidates %+v, want only %s replacing \"old text\" with \"new text\" in p/p.go and p/p_test.go", got, good)
	}
}

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func salted(key string) string {
	s := sha256.Sum256([]byte("adr-160:" + key))
	return hex.EncodeToString(s[:])
}

// TestAWideRenameCandidateIsDeclaredOnceAndNeverInAString holds ADR-160's
// wide-rename predicate on a fixture module, with floors of 4 occurrences
// across 2 files: an identifier declared twice, one named in a string, one
// named in a generated file, one used as a package name and one under the floor
// are refused; one mentioned in comments qualifies with its comments counted.
// A name used as a selector on a standard-library value (Header) cannot be told
// apart without types, so it is listed: T2's build gate is what filters it.
func TestAWideRenameCandidateIsDeclaredOnceAndNeverInAString(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":   "module example.com/m\n\ngo 1.22\n",
		"a/a.go":   "package a\n\nimport \"net/http\"\n\n// Good does the thing; Good is documented.\nfunc Good() int { return Other + Twice }\n\n// Other is a constant.\nconst Other = 1\n\nvar Twice = 2\n\nfunc InString() string { return \"InString\" }\n\nfunc InGen() {}\n\nfunc Low() {}\n\ntype T struct{ Header int }\n\nfunc h(r *http.Response) int { _ = r.Header; return T{}.Header + Other }\n",
		"b/b.go":   "package b\n\nimport \"example.com/m/a\"\n\nfunc use() int {\n\tTwice := 3\n\ta.InGen()\n\ta.InString()\n\treturn a.Good() + a.Good() + a.Other + a.Other + Twice\n}\n\nfunc header(t a.T) int { return t.Header + t.Header }\n",
		"b/gen.go": "// Code generated by fixture. DO NOT EDIT.\n\npackage b\n\nfunc gen() { _ = a.InGen }\n",
		"c/c.go":   "package c\n\nimport \"example.com/m/a\"\n\n// uses Good again\nfunc again() int { a.InGen(); return a.Good() + a.Other }\n",
	})
	got, err := MineWideRenames(root, 4, 2)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, c := range got {
		names = append(names, c.Name)
	}
	for _, refused := range []string{"Twice", "InString", "InGen", "Low", "a", "http"} {
		if slices.Contains(names, refused) {
			t.Errorf("%s is listed; the predicate refuses it", refused)
		}
	}
	for _, want := range []string{"Good", "Other", "Header"} {
		if !slices.Contains(names, want) {
			t.Errorf("%s is not listed; it meets the predicate (%v)", want, got)
		}
	}
	for _, c := range got {
		if c.Name == "Good" && (c.Occurrences != 7 || c.Files != 3) {
			t.Errorf("Good: %d occurrences in %d files, want 7 in 3 (its two comment mentions in a.go and one in c.go counted)", c.Occurrences, c.Files)
		}
	}
	if !slices.IsSortedFunc(got, func(x, y RenameCandidate) int { return strings.Compare(salted(x.Name), salted(y.Name)) }) {
		t.Errorf("candidates are not in sha256(\"adr-160:\" + name) order: %v", names)
	}
	// Declarations as go/types records them (the reviews of #426): an
	// embedded field declares its type's name again, each generic method's
	// receiver declares its type parameter again, a := that redeclares a name
	// in its own scope declares nothing, a struct field does not hide a local
	// of the same name, and a type switch's case reuses its implicit variable.
	fset := token.NewFileSet()
	var fs []*ast.File
	for name, src := range map[string]string{
		"d.go": "package d\n\ntype Inner struct{}\n\ntype Outer struct {\n\tInner\n\t*Other\n}\n\ntype Box[Elem any] struct{ v Elem }\n\nfunc (b Box[Elem]) Get() Elem { return b.v }\n\nfunc (b *Box[Elem]) Set(v Elem) { b.v = v }\n\nfunc r(p int) int {\n\tRedecl := 1\n\tRedecl, other := 2, 3\n\tp, fresh := 4, 5\n\tif true {\n\t\tRedecl := 6\n\t\t_ = Redecl\n\t}\n\treturn Redecl + other + p + fresh\n}\n",
		"e.go": "package d\n\nfunc s() {\n\ttype S struct{ Clash int }\n\tClash := 1\n\t_ = Clash\n}\n\nfunc ts(x any) {\n\tswitch Choice := x.(type) {\n\tcase int:\n\t\tChoice, fresh2 := Choice, 1\n\t\t_, _ = Choice, fresh2\n\t}\n}\n",
		// One name in two build-tagged files, and a field inside a type
		// argument of an unresolved generic: Info.Defs misses one of each,
		// the syntax does not (the third review of #426).
		"x_linux.go":   "package d\n\nfunc Shared() {}\n",
		"x_windows.go": "package d\n\nfunc Shared() {}\n",
		"g.go":         "package d\n\nimport ext \"example.com/ext\"\n\ntype A ext.Box[struct{ Clash2 int }]\n\ntype B struct{ Clash2 int }\n",
	} {
		f, err := parser.ParseFile(fset, name, src, 0)
		if err != nil {
			t.Fatal(err)
		}
		fs = append(fs, f)
	}
	decls := map[string]int{}
	countDecls(fset, fs, decls)
	for name, want := range map[string]int{"Inner": 2, "Other": 1, "Elem": 3, "Redecl": 2, "other": 1, "p": 1, "fresh": 1, "b": 2, "v": 2, "Clash": 2, "Choice": 1, "fresh2": 1, "d": 0, "Shared": 2, "Clash2": 2} {
		if decls[name] != want {
			t.Errorf("%s declared %d times, want %d", name, decls[name], want)
		}
	}
}

// TestACheckCoupledLiteralIsHeldOnceAndByATestBesideIt holds ADR-160's
// check-coupled rule as amended (Zy, "Construct from the tree"): a literal in
// a non-test file, appearing once there and in no other non-test file, that a
// test in the same directory also holds, starting with a letter, never an
// import path or a struct tag. Its new value flips the first letter's case.
func TestACheckCoupledLiteralIsHeldOnceAndByATestBesideIt(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":      "module example.com/m\n\ngo 1.22\n",
		"a/a.go":      "package a\n\nimport \"strings\"\n\ntype T struct {\n\tName string `json:\"name\"`\n}\n\nconst greeting = \"Hello world\"\n\nfunc F() string { return greeting }\n\nfunc G() string { return \"lower case value\" }\n\nfunc twice() (string, string) { return \"said twice\", \"said twice\" }\n\nfunc shared() string { return \"also in b\" }\n\nfunc num() string { return \"1st place\" }\n\nfunc far() string { return \"tested elsewhere\" }\n\nvar _ = strings.ToUpper\n",
		"a/a_test.go": "package a\n\nimport (\n\t\"strings\"\n\t\"testing\"\n)\n\nfunc TestF(t *testing.T) {\n\tif F() != \"Hello world\" || G() != \"lower case value\" || !strings.Contains(\"said twice also in b 1st place\", \"said twice\") {\n\t\tt.Fatal(\"x\")\n\t}\n\t_ = []string{\"also in b\", \"1st place\", `json:\"name\"`, \"strings\"}\n}\n",
		"b/b.go":      "package b\n\nfunc B() string { return \"also in b\" }\n",
		"c/c_test.go": "package c\n\nconst want = \"tested elsewhere\"\n",
	})
	got, err := MineCoupledLiterals(root)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]CoupledLiteral{
		"Hello world":      {File: "a/a.go", Old: "Hello world", New: "hello world", Tests: []string{"a/a_test.go"}},
		"lower case value": {File: "a/a.go", Old: "lower case value", New: "Lower case value", Tests: []string{"a/a_test.go"}},
	}
	if len(got) != len(want) {
		t.Errorf("%d candidates, want %d: %+v", len(got), len(want), got)
	}
	for _, c := range got {
		w, ok := want[c.Old]
		if !ok || c.File != w.File || c.New != w.New || !slices.Equal(c.Tests, w.Tests) {
			t.Errorf("candidate %+v, want %+v (listed: %v)", c, w, ok)
		}
	}
	if !slices.IsSortedFunc(got, func(x, y CoupledLiteral) int {
		return strings.Compare(salted(x.File+":"+x.Old), salted(y.File+":"+y.Old))
	}) {
		t.Errorf("candidates are not in sha256(\"adr-160:\" + path + \":\" + value) order: %+v", got)
	}
}

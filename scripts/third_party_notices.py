#!/usr/bin/env python3
"""Generate and check THIRD_PARTY_NOTICES from go.mod's requirements (#757).

A distributed binary carries the licence notice of every module compiled into
it. This reads, for each release target, the packages `go list -deps ./cmd/mrw` says
mrw compiles, takes the module each belongs to (and its directory in the module cache),
takes each module's licence files, and writes
them, module by module, to THIRD_PARTY_NOTICES. Any number of modules is handled:
the file is a function of the graph, so a requirement added later (ADR-213 may add
golang.org/x/sys) appears at the next run.

    scripts/third_party_notices.py            write THIRD_PARTY_NOTICES
    scripts/third_party_notices.py --check    exit 1 if it is missing, stale, or a
                                              module has no licence file

The check is the release gate: a module whose notice is missing fails it, and so
does a committed file that no longer matches go.mod.
"""
import argparse
import collections
import glob
import os
import re
import subprocess
import sys

NOTICES = "THIRD_PARTY_NOTICES"
# Whole names only: LICENSE, LICENCE.md, COPYING.txt, NOTICE, LICENSE-MIT; never a
# source file that merely starts with the word (license.go, notice_test.go).
LICENCE_FILE = re.compile(r"^(licen[cs]e|copying|notice)([-_][a-z0-9_-]+)?(\.(md|txt|markdown|rst))?$", re.IGNORECASE)
# A file that is only a NOTICE: additional text, never a licence.
NOTICE_ONLY = re.compile(r"^notice", re.IGNORECASE)
HEADER = (
    "THIRD-PARTY NOTICES\n\n"
    "mrw is built from its own source (see LICENSE) and the modules below, each under\n"
    "its own licence, reproduced here. This file is generated by\n"
    "scripts/third_party_notices.py from go.mod; do not edit it by hand.\n"
)


class MissingNotice(Exception):
    """A module in the graph has no licence file in its directory, or the Go
    licence is not vendored, or go itself failed (its own words are the message)."""


# The targets mrw is released for (the build matrix in .github/workflows/ci.yml): a
# module only one of them compiles in (an x/sys only windows imports) still ships in
# that target's archive.
TARGETS = (("linux", "amd64"), ("linux", "arm64"), ("darwin", "amd64"), ("darwin", "arm64"), ("windows", "amd64"))


def go(root, args, **env):
    """Run go in root; its own stderr is the message when it fails."""
    try:
        return subprocess.run(["go", *args], cwd=root, check=True, capture_output=True, text=True,
                              env=dict(os.environ, **env)).stdout
    except subprocess.CalledProcessError as e:
        raise MissingNotice(f"go {' '.join(args[:2])} failed: {(e.stderr or '').strip() or e}")


def graph(root):
    """Every non-main module compiled into ./cmd/mrw on any release target:
    (path, version, directory, replacement), sorted by path; replacement is "" or
    the path and version of what `replace` put in its place. A module only its
    tests or the module graph name (a dependency's own test libraries) ships
    nothing."""
    go(root, ["mod", "download"])
    fmt = ("{{if .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}\t{{.Module.Main}}\t"
           "{{with .Module.Replace}}{{.Path}} {{.Version}}{{end}}{{end}}")
    mods = set()
    for goos, goarch in TARGETS:
        out = go(root, ["list", "-deps", "-f", fmt, "./cmd/mrw"], GOOS=goos, GOARCH=goarch, CGO_ENABLED="0")
        for line in out.splitlines():
            if not line:
                continue
            path, version, directory, main, replaced = line.split("\t")
            if main != "true":
                mods.add((path, version, directory, replaced.strip()))
    return sorted(mods)


def licence_files(directory):
    """The licence and notice files at the top of a module's directory, sorted."""
    if not directory or not os.path.isdir(directory):
        return []
    return sorted(n for n in os.listdir(directory)
                  if LICENCE_FILE.match(n) and os.path.isfile(os.path.join(directory, n)))


GoLicence = collections.namedtuple("GoLicence", "version text")

# The Go standard library, and the golang.org/x code Go bundles inside it, are
# compiled into every mrw binary and licensed by Go's own BSD-3 LICENSE. Not every
# Go install has that file (Homebrew's has none), so the text is vendored beside
# this script and pinned to the toolchain go.mod names. When go.mod's `go` line
# moves, --check fails until scripts/third_party/go-LICENSE has been compared with the
# new toolchain's LICENSE (any golang.org/x/*/LICENSE under GOROOT/src/vendor is the
# same text) and go-LICENSE.version bumped; the test suite compares it with the
# installed toolchain's whenever that has one.
GO_LICENCE = os.path.join("scripts", "third_party", "go-LICENSE")


def go_directive(root):
    """The Go version go.mod names (its `go` line), or None."""
    try:
        with open(os.path.join(root, "go.mod"), encoding="utf-8") as f:
            for line in f:
                m = re.match(r"^go\s+(\S+)", line)
                if m:
                    return m.group(1)
    except FileNotFoundError:
        pass
    return None


def load_go_licence(root):
    """The vendored Go licence, checked against go.mod's toolchain."""
    try:
        with open(os.path.join(root, GO_LICENCE), encoding="utf-8", newline="") as f:
            text = f.read()
        with open(os.path.join(root, GO_LICENCE + ".version"), encoding="utf-8") as f:
            version = f.read().strip()
    except FileNotFoundError as e:
        raise MissingNotice(f"the Go standard library's licence is not vendored ({e.filename})")
    want = go_directive(root)
    if want != version:
        raise MissingNotice(
            f"go.mod names Go {want}, but {GO_LICENCE} was checked against {version}: compare it with the "
            f"new toolchain's LICENSE and set {GO_LICENCE}.version")
    return GoLicence(version, text)


def goroot_licence():
    """The installed toolchain's licence text, or None when it ships none."""
    goroot = subprocess.run(["go", "env", "GOROOT"], check=True, capture_output=True, text=True).stdout.strip()
    candidates = [os.path.join(goroot, "LICENSE")] + sorted(glob.glob(os.path.join(goroot, "src", "vendor", "golang.org", "x", "*", "LICENSE")))
    for c in candidates:
        if os.path.isfile(c):
            with open(c, encoding="utf-8", newline="") as f:
                return f.read()
    return None


def render(mods, golicence=None):
    """The notices file for mods, a list of (path, version, directory), and the
    Go standard library's licence when golicence (a GoLicence) is given."""
    parts = [HEADER]
    missing = []
    if golicence is not None:
        parts.append(f"\n{'=' * 78}\nGo standard library and the golang.org/x code it bundles (go{golicence.version})\n{'=' * 78}\n")
        parts.append(f"\n--- LICENSE ---\n\n{golicence.text.rstrip()}\n")
    for mod in mods:
        path, version, directory = mod[:3]
        replaced = mod[3] if len(mod) > 3 else ""
        names = licence_files(directory)
        # A NOTICE file is carried when there is one, but it holds no licence terms:
        # at least one LICENSE, LICENCE or COPYING file must be there.
        if not any(not NOTICE_ONLY.match(n) for n in names):
            missing.append(f"{path}@{version}")
            continue
        title = f"{path} {version}" + (f" (replaced by {replaced})" if replaced else "")
        parts.append(f"\n{'=' * 78}\n{title}\n{'=' * 78}\n")
        for n in names:
            with open(os.path.join(directory, n), encoding="utf-8", errors="replace") as f:
                parts.append(f"\n--- {n} ---\n\n{f.read().rstrip()}\n")
    if missing:
        raise MissingNotice("no licence file for: " + ", ".join(missing))
    return "".join(parts)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare, do not write")
    ap.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    args = ap.parse_args(argv)
    target = os.path.join(args.root, NOTICES)
    try:
        want = render(graph(args.root), load_go_licence(args.root))
    except MissingNotice as e:
        print(f"third_party_notices: {e}", file=sys.stderr)
        return 1
    if not args.check:
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(want)
        print(f"wrote {NOTICES}")
        return 0
    try:
        with open(target, encoding="utf-8", newline="") as f:
            have = f.read()
    except FileNotFoundError:
        print(f"third_party_notices: {NOTICES} is missing; run scripts/third_party_notices.py", file=sys.stderr)
        return 1
    if have != want:
        print(f"third_party_notices: {NOTICES} does not match go.mod's modules; run scripts/third_party_notices.py", file=sys.stderr)
        return 1
    print(f"{NOTICES} matches go.mod")
    return 0


if __name__ == "__main__":
    sys.exit(main())
